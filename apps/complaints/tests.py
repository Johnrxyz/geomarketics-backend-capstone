class ComplaintPublicSubmitTest(TestCase):
    """FS-04 — unauthenticated users can submit complaints."""

    def setUp(self):
        self.client = APIClient()
        self.url = '/api/v1/complaints/'

    def test_submit_anonymous_complaint_succeeds(self):
        payload = {
            'category': 'sanitation',
            'subject': 'Test sanitation complaint',
            'description': 'Stall area is not clean.',
            'complainant_contact': 'test@example.com',
        }
        response = self.client.post(self.url, payload, format='json')
        self.assertEqual(response.status_code, status.HTTP_201_CREATED)
        data = response.json()
        # ComplaintCreateSerializer now returns id and complaint_number
        self.assertIn('id', data)
        self.assertIn('complaint_number', data)

    def test_complaint_number_auto_generated(self):
        payload = {
            'category': 'overpricing',
            'subject': 'Price issue',
            'description': 'Vendor charged more than the DA reference price.',
        }
        response = self.client.post(self.url, payload, format='json')
        self.assertEqual(response.status_code, status.HTTP_201_CREATED)
        data = response.json()
        # Number should be CMP-XXX format (generated by model.save())
        complaint_number = data.get('complaint_number', '')
        self.assertTrue(
            complaint_number.startswith('CMP-'),
            f"Expected complaint_number starting with 'CMP-', got: {complaint_number}"
        )

    def test_submit_without_description_fails(self):
        """US-05 — required field validation."""
        payload = {
            'category': 'sanitation',
            'subject': 'Test',
            # description is required
        }
        response = self.client.post(self.url, payload, format='json')
        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)
        self.assertIn('description', response.json())

    def test_submit_without_subject_fails(self):
        payload = {
            'category': 'sanitation',
            'description': 'Some details',
            # subject is required
        }
        response = self.client.post(self.url, payload, format='json')
        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)

    def test_persisted_to_database(self):
        """RE-04 — submitted complaint is stored in the database."""
        payload = {
            'category': 'noise',
            'subject': 'Loud vendor',
            'description': 'Excessive noise from stall area.',
        }
        response = self.client.post(self.url, payload, format='json')
        self.assertEqual(response.status_code, status.HTTP_201_CREATED)
        data = response.json()
        pk = data['id']
        self.assertTrue(Complaint.objects.filter(pk=pk).exists())
        stored = Complaint.objects.get(pk=pk)
        self.assertEqual(stored.description, payload['description'])
        self.assertEqual(stored.status, 'open')


class ComplaintAccessControlTest(TestCase):
    """SE-04, P1-03 — role-based access to complaint detail."""

    def setUp(self):
        self.client = APIClient()
        self.url_base = '/api/v1/complaints/'

        # Admin user
        self.admin = User.objects.create_user(
            username='admin_test', password='adminpass123', role='admin'
        )
        # Customer user 1 (complaint owner)
        self.customer1 = User.objects.create_user(
            username='customer1', password='custpass123', role='customer'
        )
        # Customer user 2 (should NOT see customer1's complaint)
        self.customer2 = User.objects.create_user(
            username='customer2', password='custpass456', role='customer'
        )

        # Create a complaint belonging to customer1
        self.complaint = Complaint.objects.create(
            complainant=self.customer1,
            category='sanitation',
            subject='Test complaint',
            description='Complaint owned by customer1.',
        )

    def _auth_as(self, user):
        resp = self.client.post('/api/v1/auth/login/', {
            'username': user.username,
            'password': user.password if hasattr(user, '_password') else 'custpass123'
        }, format='json')
        if resp.status_code == 200:
            self.client.credentials(HTTP_AUTHORIZATION=f"Bearer {resp.json()['access']}")

    def _login(self, username, password):
        resp = self.client.post('/api/v1/auth/login/', {
            'username': username, 'password': password
        }, format='json')
        self.assertEqual(resp.status_code, 200, f"Login failed for {username}")
        self.client.credentials(HTTP_AUTHORIZATION=f"Bearer {resp.json()['access']}")

    def test_customer1_can_see_own_complaint(self):
        self._login('customer1', 'custpass123')
        response = self.client.get(f'{self.url_base}{self.complaint.pk}/')
        self.assertEqual(response.status_code, status.HTTP_200_OK)
        self.assertEqual(response.json()['id'], self.complaint.pk)

    def test_customer2_cannot_see_customer1_complaint(self):
        """P1-03 fix verification — cross-user retrieve must be blocked."""
        self._login('customer2', 'custpass456')
        response = self.client.get(f'{self.url_base}{self.complaint.pk}/')
        # Should be 404 (not found in their filtered queryset) not 200
        self.assertEqual(response.status_code, status.HTTP_404_NOT_FOUND)

    def test_admin_can_see_any_complaint(self):
        self._login('admin_test', 'adminpass123')
        response = self.client.get(f'{self.url_base}{self.complaint.pk}/')
        self.assertEqual(response.status_code, status.HTTP_200_OK)

    def test_unauthenticated_cannot_list_complaints(self):
        self.client.credentials()  # clear auth
        response = self.client.get(self.url_base)
        self.assertEqual(response.status_code, status.HTTP_401_UNAUTHORIZED)


class ComplaintAdminWorkflowTest(TestCase):
    """RE-01 — admin can update status; customer cannot."""

    def setUp(self):
        self.client = APIClient()
        self.admin = User.objects.create_user(
            username='admin_wf', password='adminwf123', role='admin'
        )
        self.customer = User.objects.create_user(
            username='cust_wf', password='custwf123', role='customer'
        )
        self.complaint = Complaint.objects.create(
            category='safety',
            subject='Safety hazard',
            description='Broken floor tiles near stall B-12.',
        )

    def _login(self, username, password):
        resp = self.client.post('/api/v1/auth/login/', {
            'username': username, 'password': password
        }, format='json')
        self.assertEqual(resp.status_code, 200)
        self.client.credentials(HTTP_AUTHORIZATION=f"Bearer {resp.json()['access']}")

    def test_admin_can_update_status_to_reviewing(self):
        self._login('admin_wf', 'adminwf123')
        url = f'/api/v1/complaints/{self.complaint.pk}/update-status/'
        response = self.client.patch(url, {'status': 'reviewing'}, format='json')
        self.assertEqual(response.status_code, status.HTTP_200_OK)
        self.complaint.refresh_from_db()
        self.assertEqual(self.complaint.status, 'reviewing')

    def test_customer_cannot_update_status(self):
        self._login('cust_wf', 'custwf123')
        url = f'/api/v1/complaints/{self.complaint.pk}/update-status/'
        response = self.client.patch(url, {'status': 'resolved'}, format='json')
        # Customer is not admin — should be 403
        self.assertEqual(response.status_code, status.HTTP_403_FORBIDDEN)

    def test_invalid_status_rejected(self):
        self._login('admin_wf', 'adminwf123')
        url = f'/api/v1/complaints/{self.complaint.pk}/update-status/'
        response = self.client.patch(url, {'status': 'invalid_status'}, format='json')
        self.assertEqual(response.status_code, status.HTTP_400_BAD_REQUEST)


class ComplaintPrivacyTest(TestCase):
    """
    SE-01 / SE-03 — Complainant identity must not be visible to vendors.
    Vendors can see a complaint filed against their stall but cannot identify WHO filed it.
    Admins retain full visibility for governance purposes.
    """

    def setUp(self):
        self.client = APIClient()
        self.url_base = '/api/v1/complaints/'

        self.admin = User.objects.create_user(
            username='admin_priv', password='adminpriv123', role='admin'
        )
        self.vendor_user = User.objects.create_user(
            username='vendor_priv', password='vendorpriv123', role='vendor'
        )
        from apps.vendors.models import MarketSection, Stall, Vendor
        section = MarketSection.objects.create(code='PV', name='Privacy Section')
        stall = Stall.objects.create(
            stall_number='PV-01', section=section,
            category='Test', status='owner', building='main', floor='1'
        )
        self.vendor_profile = Vendor.objects.create(
            user=self.vendor_user, stall=stall,
            first_name='Vendor', last_name='Test'
        )
        # Complaint against vendor's stall with a real complainant email
        self.complaint = Complaint.objects.create(
            vendor=self.vendor_profile,
            stall=stall,
            category='sanitation',
            subject='Sanitation issue',
            description='The stall is unclean.',
            complainant_contact='secret@example.com',
            complainant_name='Confidential Person',
        )

    def _login(self, username, password):
        resp = self.client.post('/api/v1/auth/login/', {
            'username': username, 'password': password
        }, format='json')
        self.assertEqual(resp.status_code, 200, f"Login failed for {username}")
        self.client.credentials(HTTP_AUTHORIZATION=f"Bearer {resp.json()['access']}")

    def test_vendor_list_omits_complainant_identity_fields(self):
        """SE-01 — vendor complaint list must not expose complainant email/name."""
        self._login('vendor_priv', 'vendorpriv123')
        response = self.client.get(self.url_base)
        self.assertEqual(response.status_code, 200)
        results = response.json().get('results', response.json())
        for c in results:
            self.assertNotIn('complainant_contact', c,
                             "complainant_contact must NOT appear in vendor list")
            self.assertNotIn('complainant_name', c,
                             "complainant_name must NOT appear in vendor list")
            self.assertNotIn('complainant', c,
                             "complainant FK must NOT appear in vendor list")

    def test_vendor_detail_omits_complainant_identity_fields(self):
        """SE-01 — vendor complaint detail must not expose complainant email/name."""
        self._login('vendor_priv', 'vendorpriv123')
        response = self.client.get(f'{self.url_base}{self.complaint.pk}/')
        self.assertEqual(response.status_code, 200)
        data = response.json()
        self.assertNotIn('complainant_contact', data,
                         "complainant_contact must NOT appear in vendor detail")
        self.assertNotIn('complainant_name', data,
                         "complainant_name must NOT appear in vendor detail")

    def test_admin_retains_full_complainant_visibility(self):
        """SE-04 — admin must still see complainant_contact for governance."""
        self._login('admin_priv', 'adminpriv123')
        response = self.client.get(f'{self.url_base}{self.complaint.pk}/')
        self.assertEqual(response.status_code, 200)
        data = response.json()
        self.assertIn('complainant_contact', data)
        self.assertEqual(data['complainant_contact'], 'secret@example.com')
        self.assertIn('complainant_name', data)

    def test_anonymous_create_response_scope(self):
        """SE-03 — 201 response returns id/complaint_number; not the full complaint record."""
        self.client.credentials()
        payload = {
            'category': 'safety',
            'subject': 'Safety concern',
            'description': 'Loose flooring.',
            'complainant_contact': 'anon@example.com',
        }
        response = self.client.post(self.url_base, payload, format='json')
        self.assertEqual(response.status_code, 201)
        data = response.json()
        self.assertIn('id', data)
        self.assertIn('complaint_number', data)
        # The create serializer does echo back complainant_contact (user typed it);
        # the critical rule is it is NOT visible to other roles (tested above).
        stored = Complaint.objects.get(pk=data['id'])
        self.assertEqual(stored.complainant_contact, 'anon@example.com')
        # Verify full complainant serializer is not returned on create
        self.assertNotIn('complainant', data)

