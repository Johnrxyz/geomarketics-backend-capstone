from rest_framework import viewsets, permissions, status
from rest_framework.decorators import action
from rest_framework.response import Response
from rest_framework.pagination import PageNumberPagination
from django_filters.rest_framework import DjangoFilterBackend
from rest_framework.filters import SearchFilter, OrderingFilter
from .models import CommodityCategory, Commodity
from .serializers import CommodityCategorySerializer, CommoditySerializer


class LargeResultsSetPagination(PageNumberPagination):
    page_size = 1000
    page_size_query_param = 'page_size'
    max_page_size = 5000


class IsAdminRole(permissions.BasePermission):
    def has_permission(self, request, view):
        return request.user.is_authenticated and request.user.role == 'admin'


class IsAdminOrPublic(permissions.BasePermission):
    def has_permission(self, request, view):
        if request.method in permissions.SAFE_METHODS:
            return True  # public read for price data
        return request.user.is_authenticated and request.user.role == 'admin'


class CommodityCategoryViewSet(viewsets.ModelViewSet):
    queryset = CommodityCategory.objects.all()
    serializer_class = CommodityCategorySerializer
    permission_classes = [IsAdminOrPublic]
    ordering_fields = ['order', 'name']


class CommodityViewSet(viewsets.ModelViewSet):
    queryset = Commodity.objects.select_related('category').filter(is_active=True)
    serializer_class = CommoditySerializer
    permission_classes = [IsAdminOrPublic]
    filter_backends = [DjangoFilterBackend, SearchFilter, OrderingFilter]
    filterset_fields = ['category', 'unit', 'is_active']
    search_fields = ['name']
    ordering_fields = ['name', 'category__order', 'order']





class PriceSnapshotViewSet(viewsets.ReadOnlyModelViewSet):
    """
    Authoritative source for all analytics and public statistics.
    Provides read-only access to PriceSnapshot records generated by the ingestion pipeline.
    """
    from .models import PriceSnapshot
    queryset = PriceSnapshot.objects.select_related('market', 'commodity', 'commodity__category').all()
    from .serializers import PriceSnapshotSerializer
    serializer_class = PriceSnapshotSerializer
    permission_classes = [permissions.AllowAny]
    pagination_class = LargeResultsSetPagination
    filter_backends = [DjangoFilterBackend, SearchFilter, OrderingFilter]
    filterset_fields = ['market', 'commodity', 'commodity__category', 'survey_date', 'data_quality']
    search_fields = ['market__name', 'commodity__name']
    ordering_fields = ['survey_date', 'created_at']
    ordering = ['-survey_date']

